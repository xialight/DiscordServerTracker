import { EmbedBuilder, SlashCommandBuilder } from 'discord.js';
import { geminiSearchAnswer } from '../helpers/gemini.js';

const MAX_DESCRIPTION_LENGTH = 4000;
// Answer text is LLM-generated from arbitrary web content, so strip Markdown
// control characters before dropping it into an embed to avoid broken formatting.
const MARKDOWN_CHARS_REGEX = /[*_~`|]/g;

function sanitize(text) {
  return text.replace(MARKDOWN_CHARS_REGEX, '');
}

function truncate(text, length) {
  return text.length > length ? `${text.slice(0, length - 1)}…` : text;
}

export default {
  data: new SlashCommandBuilder()
    .setName('search')
    .setDescription('Gets a Google-Search-grounded AI overview answer (via Gemini) for a query.')
    .addStringOption((option) =>
      option.setName('query').setDescription('What to ask or search for.').setRequired(true)
    ),

  async execute(interaction) {
    await interaction.deferReply();

    const query = interaction.options.getString('query');

    let result;
    try {
      result = await geminiSearchAnswer(query);
    } catch (error) {
      console.error('Gemini search error:', error);
      return interaction.editReply('Search failed — the search provider may be down or rate-limited.');
    }

    if (!result.available) {
      return interaction.editReply(
        `No AI overview available for **${sanitize(query)}**. Try rephrasing it as a question.`
      );
    }

    const embed = new EmbedBuilder()
      .setColor(0x4285f4)
      .setTitle(`AI overview: "${sanitize(query)}"`)
      .setDescription(truncate(sanitize(result.text), MAX_DESCRIPTION_LENGTH))
      .setFooter({ text: 'Generated by Gemini, grounded in Google Search — may be inaccurate' });

    await interaction.editReply({ embeds: [embed] });
  },
};
